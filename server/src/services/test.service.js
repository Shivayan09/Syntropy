import Groq from "groq-sdk";
import Test from "../models/test.model.js";

export async function generateTest(data, userId) {
    const groq = new Groq({
        apiKey: process.env.GROQ_API_KEY,
    });

    const { subjects, difficulty, questions, time } = data;

    // distribute questions equally
    const perSubject = Math.floor(questions / subjects.length);
    let remaining = questions % subjects.length;

    const distribution = subjects.map((s) => {
        const count = perSubject + (remaining > 0 ? 1 : 0);
        remaining--;
        return { subject: s, count };
    });

    const distributionText = distribution
        .map(d => `${d.count} questions from ${d.subject}`)
        .join("\n");

    const completion = await groq.chat.completions.create({
        model: "openai/gpt-oss-120b",
        temperature: 0.3,
        messages: [
            {
                role: "system",
                content:
                    "You generate structured MCQ tests. Always follow distribution exactly and return valid JSON only."
            },
            {
                role: "user",
                content: `
Generate ${questions} MCQs

Difficulty: ${difficulty}

Distribution:
${distributionText}

Rules:
- 4 options per question
- only one correct answer
- mix difficulty within ${difficulty}
- avoid duplicate questions
- return ONLY JSON

Return JSON:
[
{
question:"",
subject:"",
options:["","","",""],
correct_answer:"",
explanation:""
}
]
`
            }
        ]
    });

    // ---------- parse AI response ----------
    const aiText = completion.choices[0].message.content;
    const parsed = JSON.parse(aiText);

    // ---------- map to schema ----------
    const formattedQuestions = parsed.map(q => ({
        question: q.question,
        options: q.options,
        correctAnswer: q.options.findIndex(
            opt => opt === q.correct_answer
        ),
        explanation: q.explanation || "",
        subject: q.subject || null,
        difficulty
    }));

    // ---------- create test ----------
    const test = await Test.create({
        title: `AI Test - ${subjects.join(", ")}`,
        description: "Generated by AI",
        type: "generated",
        createdBy: userId,
        difficulty,
        subjects,
        totalQuestions: formattedQuestions.length,
        duration: time,
        questions: formattedQuestions,
        isPublished: true
    });

    return test;
}