import Groq from "groq-sdk";
import Test from "../models/test.model.js";

// ===== AUTO DISTRIBUTION =====
function generateDistribution(totalMarks) {
    let remaining = totalMarks;
    const result = { 1: 0, 2: 0, 5: 0 };

    while (remaining > 0) {
        if (remaining >= 5 && result[5] <= result[2]) {
            result[5]++;
            remaining -= 5;
        } else if (remaining >= 2 && result[2] <= result[1]) {
            result[2]++;
            remaining -= 2;
        } else {
            result[1]++;
            remaining -= 1;
        }
    }

    return Object.entries(result)
        .filter(([_, count]) => count > 0)
        .map(([marks, count]) => ({ marks: Number(marks), count }));
}

// ===== MAIN GENERATOR =====
export async function generateSubjectiveTest(data, userId) {
    const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });

    const { subjects, difficulty, totalMarks, time, college, semester } = data;

    const markDistribution = generateDistribution(totalMarks);

    const distributionText = markDistribution
        .map(d => `${d.count} questions of ${d.marks} marks`)
        .join("\n");

    const completion = await groq.chat.completions.create({
        model: "openai/gpt-oss-120b",
        temperature: 0.3,
        messages: [
            {
                role: "system",
                content: "You generate structured subjective tests. Follow distribution strictly. Return valid JSON only."
            },
            {
                role: "user",
                content: `
Generate a subjective test.

Student Context:
- College: ${college || "Not specified"}
- Semester: ${semester || "Not specified"}

Subjects: ${subjects.join(", ")}
Difficulty: ${difficulty}
Total Marks: ${totalMarks}

Distribution:
${distributionText}

Rules:
- STRICTLY follow distribution
- Each question must match assigned marks
- Include expected_answer
- Include key_points
- Avoid duplicates
- Return ONLY JSON

Format:
[
{
question:"",
marks:5,
expected_answer:"",
key_points:["",""],
subject:""
}
]
`
            }
        ]
    });

    let aiText = completion.choices[0].message.content;

    // clean AI garbage
    aiText = aiText.replace(/```json|```/g, "").trim();

    const parsed = JSON.parse(aiText);

    const formattedQuestions = parsed.map(q => ({
        question: q.question,
        marks: q.marks,
        expectedAnswer: q.expected_answer,
        keyPoints: q.key_points || [],
        subject: q.subject || null,
        difficulty
    }));

    const test = await Test.create({
        title: `AI Subjective Test - ${subjects.join(", ")}`,
        description: "Generated by AI",
        type: "generated",
        createdBy: userId,
        difficulty,
        subjects,
        totalQuestions: formattedQuestions.length,
        duration: time,
        questions: formattedQuestions,
        testFormat: "subjective",
        totalMarks,
        markDistribution,
        isPublished: true
    });

    return test;
}