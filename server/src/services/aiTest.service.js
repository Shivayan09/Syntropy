import Groq from "groq-sdk";
import Test from "../models/test.model.js";
import { jsonrepair } from "jsonrepair";
import { getNextTestTitle } from "../utils/testTitle.utils.js";

export async function generateTest(data, userId) {
    const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });

    const { subjects, difficulty, questions, time, college, semester } = data;

    if (!subjects || subjects.length === 0) {
        throw new Error("Subjects required");
    }

    if (questions > 30) {
        throw new Error("Too many questions requested (max 30)");
    }

    const perSubject = Math.floor(questions / subjects.length);
    let remaining = questions % subjects.length;

    const distribution = subjects.map((s) => {
        const count = perSubject + (remaining > 0 ? 1 : 0);
        remaining--;
        return { subject: s, count };
    });

    const distributionText = distribution.map((d) => `${d.count} questions from ${d.subject}`).join("\n");

    const completion = await groq.chat.completions.create({
        model: "openai/gpt-oss-120b",
        temperature: 0.3,
        messages: [
            {
                role: "system",
                content: `
You generate structured MCQ tests.

STRICT RULES:
- Return strictly valid JSON
- Use double quotes for ALL keys and strings
- No trailing commas
- No markdown
- No explanations outside JSON
- Output must be parseable by JSON.parse
- Follow distribution exactly
`
            },
            {
                role: "user",
                content: `
Generate ${questions} MCQs.

Student Context:
- College: ${college || "Not specified"}
- Semester: ${semester || "Not specified"}

Instructions:
- Lower semester → conceptual
- Higher semester → analytical

Difficulty: ${difficulty}

Distribution:
${distributionText}

Rules:
- EXACTLY 4 options per question
- Only one correct answer
- correct_answer MUST match one option EXACTLY
- Do not leave any field empty
- Avoid duplicates
- Keep explanations short

Return JSON:
[
{
"question": "",
"subject": "",
"options": ["", "", "", ""],
"correct_answer": "",
"explanation": ""
}
]
`
            }
        ]
    });

    const aiText = completion.choices[0].message.content;

    let parsed;

    try {
        const cleaned = aiText.replace(/```json/gi, "").replace(/```/g, "").trim();

        const start = cleaned.indexOf("[");
        const end = cleaned.lastIndexOf("]");

        if (start === -1 || end === -1) {
            throw new Error("No JSON array found in AI response");
        }

        const jsonString = cleaned.slice(start, end + 1);

        const repaired = jsonrepair(jsonString);

        parsed = JSON.parse(repaired);

        if (!Array.isArray(parsed)) {
            throw new Error("Parsed response is not an array");
        }

    } catch (err) {
        throw new Error("AI returned invalid JSON");
    }

    const formattedQuestions = parsed
        .map((q, idx) => {
            if (!q?.question || !Array.isArray(q?.options) || q.options.length !== 4) {
                return null;
            }

            const correctIndex = q.options.findIndex(
                (opt) =>
                    opt?.trim().toLowerCase() ===
                    q.correct_answer?.trim().toLowerCase()
            );

            if (correctIndex === -1) {
                return null;
            }

            return {
                question: q.question,
                options: q.options,
                correctAnswer: correctIndex,
                explanation: q.explanation || "",
                subject: q.subject || null,
                difficulty
            };
        })
        .filter(Boolean);

    if (formattedQuestions.length < questions * 0.7) {
        throw new Error("Too many invalid questions generated by AI");
    }

    const test = await Test.create({
        title: await getNextTestTitle(userId),
        description: "Generated by AI",
        type: "generated",
        testFormat: "mcq",
        createdBy: userId,
        difficulty,
        subjects,
        totalQuestions: formattedQuestions.length,
        duration: time,
        questions: formattedQuestions,
        isPublished: true
    });

    return test;
}
